// Tecken med accent: bastecken + två rader som ritas ovanför
const ACCENT = {
  'Å': ['A', ['..#..', '.#.#.']],
  'Ä': ['A', ['.#.#.', '.....']],
  'Ö': ['O', ['.#.#.', '.....']],
};

export const GLYPH_W = 5;
export const GLYPH_H = 7;
const ADVANCE = GLYPH_W + 1; // tecken + 1 pixel mellanrum
const TOP = 2;               // extra rader ovanför för accenter

const cache = new Map();     // "tecken|färg" -> offscreen-canvas

// Finns tecknet i typsnittet? (versaler/gemener behandlas lika)
export function hasGlyph(ch) {
  const c = ch.toUpperCase();
  return c in G || c in ACCENT;
}

// Alla tecken i strängen som saknas i typsnittet
export function missingChars(str) {
  return [...str].filter((ch) => !hasGlyph(ch));
}

function glyphCanvas(ch, color) {
  const key = `${ch}|${color}`;
  let cv = cache.get(key);
  if (cv) return cv;
  cv = document.createElement('canvas');
  cv.width = GLYPH_W;
  cv.height = GLYPH_H + TOP;
  const g = cv.getContext('2d');
  g.fillStyle = color;
  const paint = (rows, y0) => rows.forEach((row, y) => {
    for (let x = 0; x < GLYPH_W; x++) if (row[x] === '#') g.fillRect(x, y0 + y, 1, 1);
  });
  if (ACCENT[ch]) {
    paint(G[ACCENT[ch][0]], TOP);
    paint(ACCENT[ch][1], 0);
  } else {
    paint(G[ch], TOP);
  }
  cache.set(key, cv);
  return cv;
}

export function textWidth(str, scale = 1) {
  return Math.max(0, str.length * ADVANCE - 1) * scale;
}

// Ritar text. align: 'left' | 'center' | 'right'. x,y är övre vänstra hörnet av basraden.
export function drawText(ctx, str, x, y, { color = '#fff', scale = 1, align = 'left' } = {}) {
  const s = String(str).toUpperCase();
  let px = Math.round(align === 'center' ? x - textWidth(s, scale) / 2
    : align === 'right' ? x - textWidth(s, scale) : x);
  const py = Math.round(y);
  for (const ch of s) {
    if (hasGlyph(ch) && ch !== ' ') {
      ctx.drawImage(glyphCanvas(ch, color), px, py - TOP * scale, GLYPH_W * scale, (GLYPH_H + TOP) * scale);
    }
    px += ADVANCE * scale;
  }
}
